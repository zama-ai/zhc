use zhc_builder::{IntegerCiphertextSpec, add, cmp_gt};
use zhc_config::hpu::{HpuConfig, PhysicalConfig};
use zhc_ir::IR;
use zhc_langs::ioplang::IopLang;
use zhc_utils::assert_display_is;

use zhc_pipeline::{
    SchedPolicy, extract_lut_registry,
    passes::{
        hpu_allocate_registers, hpu_generate_translation_table, hpu_schedule_legacy,
        lower_iop_to_hpu,
    },
};

fn pipeline(ir: &IR<IopLang>) -> Vec<u32> {
    let lut_reg = extract_lut_registry(&ir);
    let ir = lower_iop_to_hpu(&ir).output;
    let config = HpuConfig::from(PhysicalConfig::gaussian_64b_fast());
    let scheduled = hpu_schedule_legacy(
        &ir,
        &config,
        SchedPolicy::AsLateAsPossible,
        SchedPolicy::AsLateAsPossible,
    );
    let allocated = hpu_allocate_registers(&scheduled, &config, &lut_reg);
    hpu_generate_translation_table(&allocated, None)
}

fn format_binary_vec(inp: &Vec<u32>) -> String {
    inp.iter()
        .map(|a| format!("{:#034b},", a))
        .collect::<Vec<_>>()
        .join("\n")
}

